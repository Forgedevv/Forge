import { z } from 'zod';
import { IMAGE_MAX_BYTES, IMAGE_TYPES } from './validation';

/**
 * LOCKED ZONE. Server-side client of the FORGE upload endpoint (apps/web). The site holds no
 * storage credential: the FORGE API checks the wallet authorization again, then hands out a
 * short-lived presigned PUT URL for the coin image (write-once key inside this launchpad's folder)
 * and writes the metadata JSON itself once the image is verified.
 *
 * CONTRACT (version 1). `{api}` is `NEXT_PUBLIC_FORGE_API_URL`, or by default the origin of
 * `NEXT_PUBLIC_FORGE_RPC_RELAY_URL` (the relay is served by apps/web). JSON bodies are strict.
 *
 * 1. `POST {api}/api/launchpads/{slug}/uploads`
 *    Request: `UploadRequest` below: the fresh mint (generated by the site server), the creator
 *    wallet, the coin texts, the first buy, the image descriptor (type, size, SHA-256) and the
 *    wallet authorization exactly as signed (`auth.ts`: host, nonce, issuedAt, signature).
 *    FORGE must: rebuild the message with `buildLaunchAuthMessage`, verify the ed25519 signature,
 *    accept `auth.host` only if it is a domain of launchpad `{slug}`, check `issuedAt` freshness,
 *    consume `(wallet, nonce)` durably (idempotent: an identical retry returns the same answer,
 *    another body with the same nonce is 409), refuse a mint already used, enforce the type
 *    allowlist and the 2 MB cap, rate-limit per wallet and per launchpad, refuse a launchpad that
 *    is not live.
 *    Response 200: `UploadTicket`: `image.uploadUrl` is a presigned PUT (expires within 10 min)
 *    on the key `launchpads/{slug}/images/{mint}.{ext}`, signed with `Content-Type`,
 *    `If-None-Match: *` (write-once) and `x-amz-checksum-sha256` (base64 of the SHA-256), all
 *    listed in `image.headers`; `image.publicUrl` and `metadata.publicUrl`
 *    (`launchpads/{slug}/metadata/{mint}.json`) are the final public URLs.
 * 2. `PUT {image.uploadUrl}` with exactly `image.headers` and the image bytes. 2xx: stored.
 *    412: the key already exists, nothing was overwritten.
 * 3. `POST {api}/api/launchpads/{slug}/uploads/{uploadId}/complete`, body `{ "mint": "<mint>" }`.
 *    FORGE reads the stored image back, checks size, SHA-256 and magic bytes (PNG, JPEG, WebP,
 *    GIF), deletes it if anything differs, then writes the metadata JSON
 *    `{ name, symbol, description, image }` write-once. Idempotent. Response 200: `UploadReceipt`.
 *
 * Errors: non-2xx with `{ error: { code, message } }`; 429 carries `Retry-After` (seconds).
 * Nothing here falls back to storage credentials: when the endpoint is missing or refuses,
 * coin creation fails closed.
 */

export const UPLOAD_CONTRACT_VERSION = 1;
/** Uploads are refused when the ticket expires sooner than this. */
const MIN_TICKET_LIFETIME_MS = 15_000;

const Hex64 = z.string().regex(/^[0-9a-f]{64}$/);
const SolanaAddress = z.string().regex(/^[1-9A-HJ-NP-Za-km-z]{32,44}$/);
const HttpsUrl = z
  .string()
  .max(2048)
  .refine((value) => {
    try {
      return new URL(value).protocol === 'https:';
    } catch {
      return false;
    }
  }, 'must be an https URL');

export const UploadRequest = z
  .object({
    version: z.literal(UPLOAD_CONTRACT_VERSION),
    mint: SolanaAddress,
    wallet: SolanaAddress,
    coin: z
      .object({
        name: z.string().min(1).max(32),
        symbol: z.string().min(1).max(10),
        description: z.string().max(500),
      })
      .strict(),
    firstBuyLamports: z.string().regex(/^\d{1,20}$/),
    image: z
      .object({
        contentType: z.enum(IMAGE_TYPES),
        size: z.number().int().min(1).max(IMAGE_MAX_BYTES),
        sha256: Hex64,
      })
      .strict(),
    auth: z
      .object({
        host: z.string().min(1).max(253),
        nonce: z.string().regex(/^[0-9a-f]{32}$/),
        issuedAt: z.string().min(1).max(32),
        signature: z.string().min(1).max(200),
      })
      .strict(),
  })
  .strict();
export type UploadRequest = z.infer<typeof UploadRequest>;

/** The only headers the PUT may carry, and what each must be. */
const PutHeaders = z
  .object({
    'content-type': z.enum(IMAGE_TYPES),
    'if-none-match': z.literal('*'),
    'x-amz-checksum-sha256': z.string().regex(/^[A-Za-z0-9+/]{43}=$/),
    'cache-control': z.string().max(100).optional(),
  })
  .strict();

export const UploadTicket = z.object({
  uploadId: z.string().regex(/^[A-Za-z0-9_-]{8,64}$/),
  expiresAt: z.string().datetime(),
  image: z.object({
    uploadUrl: HttpsUrl,
    method: z.literal('PUT'),
    headers: z.record(z.string()),
    publicUrl: HttpsUrl,
  }),
  metadata: z.object({ publicUrl: HttpsUrl }),
});
export type UploadTicket = z.infer<typeof UploadTicket>;

export const UploadReceipt = z.object({
  image: z.object({ publicUrl: HttpsUrl, sha256: Hex64 }),
  metadata: z.object({ publicUrl: HttpsUrl, sha256: Hex64 }),
});
export type UploadReceipt = z.infer<typeof UploadReceipt>;

export type UploadErrorCode =
  'not_configured' | 'unreachable' | 'refused' | 'rate_limited' | 'invalid_answer' | 'conflict';

export class UploadError extends Error {
  constructor(
    readonly code: UploadErrorCode,
    message: string,
    readonly status?: number,
    /** Seconds, from `Retry-After` on a 429. */
    readonly retryAfter?: number,
  ) {
    super(message);
    this.name = 'UploadError';
  }
}

export interface HttpResponseLike {
  ok: boolean;
  status: number;
  headers: { get(name: string): string | null };
  json(): Promise<unknown>;
}

export type UploadFetch = (
  url: string,
  init: { method: string; headers: Record<string, string>; body: string | Uint8Array },
) => Promise<HttpResponseLike>;

export interface UploadClientOptions {
  /** Origin (or base URL) of the FORGE API. */
  apiBase: string;
  slug: string;
  /** `R2_PUBLIC_URL`: when set, every public URL must live under it. */
  publicBaseUrl?: string | null;
  /**
   * Extra headers for the two FORGE API calls only (ticket and complete), e.g. the per-launchpad
   * server token (`server-relay.ts`). Never sent with the presigned storage PUT.
   */
  forgeHeaders?: Record<string, string>;
  fetch?: UploadFetch;
  /** Extra attempts on network errors and 5xx. Default 2. */
  retries?: number;
  sleep?: (ms: number) => Promise<void>;
  now?: () => number;
}

export interface UploadedCoin {
  imageUrl: string;
  metadataUrl: string;
}

export interface UploadClient {
  /** Runs the three steps; resolves with the public URLs once the metadata is written. */
  uploadCoin(request: UploadRequest, image: Uint8Array): Promise<UploadedCoin>;
}

const SLUG = /^[a-z0-9](?:[a-z0-9-]{0,62}[a-z0-9])?$/;
const defaultSleep = (ms: number) => new Promise<void>((resolve) => setTimeout(resolve, ms));

/**
 * FORGE API base URL: `NEXT_PUBLIC_FORGE_API_URL` when set, else the origin of the RPC relay URL.
 * https only (http is accepted for localhost during development). Null when unusable.
 */
export function resolveForgeApiBase(
  apiUrl: string | undefined,
  relayUrl: string | undefined,
): string | null {
  for (const raw of [apiUrl, relayUrl]) {
    if (!raw) continue;
    try {
      const url = new URL(raw);
      const local = url.hostname === 'localhost' || url.hostname === '127.0.0.1';
      if (url.protocol !== 'https:' && !(url.protocol === 'http:' && local)) return null;
      if (url.username || url.password) return null;
      return raw === apiUrl ? url.toString().replace(/\/+$/, '') : url.origin;
    } catch {
      return null;
    }
  }
  return null;
}

function bytesToBase64(bytes: Uint8Array): string {
  return Buffer.from(bytes).toString('base64');
}

function hexToBytes(hex: string): Uint8Array {
  return Uint8Array.from(Buffer.from(hex, 'hex'));
}

function isUnder(url: string, base: string | null | undefined): boolean {
  if (!base) return true;
  try {
    const root = new URL(base);
    const target = new URL(url);
    const prefix = root.pathname.replace(/\/+$/, '') + '/';
    return target.origin === root.origin && target.pathname.startsWith(prefix);
  } catch {
    return false;
  }
}

async function readError(res: HttpResponseLike): Promise<string> {
  try {
    const payload = (await res.json()) as { error?: { message?: unknown } | unknown };
    const error = payload?.error as { message?: unknown } | string | undefined;
    if (typeof error === 'string') return error.slice(0, 200);
    if (error && typeof error.message === 'string') return error.message.slice(0, 200);
  } catch {
    // Fall through.
  }
  return `The FORGE upload service answered ${res.status}.`;
}

export function createUploadClient(options: UploadClientOptions): UploadClient {
  if (!SLUG.test(options.slug)) {
    throw new UploadError('not_configured', 'Invalid launchpad slug.');
  }
  const base = options.apiBase.replace(/\/+$/, '');
  const doFetch: UploadFetch =
    options.fetch ??
    ((url, init) =>
      fetch(url, {
        method: init.method,
        headers: init.headers,
        body: init.body as BodyInit,
        redirect: 'error',
      }));
  const retries = options.retries ?? 2;
  const sleep = options.sleep ?? defaultSleep;
  const now = options.now ?? Date.now;
  const root = `${base}/api/launchpads/${encodeURIComponent(options.slug)}/uploads`;
  const forgeHeaders = { ...(options.forgeHeaders ?? {}), 'Content-Type': 'application/json' };

  /** Sends with retries on network errors and 5xx. Returns the last response. */
  async function send(
    url: string,
    init: Parameters<UploadFetch>[1],
    onAttempt?: (attempt: number) => void,
  ): Promise<HttpResponseLike> {
    for (let attempt = 0; attempt <= retries; attempt++) {
      if (attempt > 0) await sleep(300 * 2 ** (attempt - 1));
      onAttempt?.(attempt);
      let res: HttpResponseLike;
      try {
        res = await doFetch(url, init);
      } catch {
        continue;
      }
      if (res.status >= 500 && attempt < retries) continue;
      return res;
    }
    throw new UploadError(
      'unreachable',
      'The FORGE upload service is unreachable. Try again in a moment.',
    );
  }

  async function refuse(res: HttpResponseLike): Promise<never> {
    const message = await readError(res);
    if (res.status === 429) {
      const retryAfter = Number(res.headers.get('retry-after'));
      throw new UploadError(
        'rate_limited',
        message,
        429,
        Number.isFinite(retryAfter) ? retryAfter : undefined,
      );
    }
    if (res.status === 409) throw new UploadError('conflict', message, 409);
    throw new UploadError('refused', message, res.status);
  }

  function checkTicket(ticket: UploadTicket, request: UploadRequest): Record<string, string> {
    const invalid = (why: string): never => {
      throw new UploadError(
        'invalid_answer',
        `The FORGE upload service answer is invalid (${why}).`,
      );
    };
    const expires = Date.parse(ticket.expiresAt);
    if (!Number.isFinite(expires) || expires - now() < MIN_TICKET_LIFETIME_MS) invalid('expired');
    const headers: Record<string, string> = {};
    for (const [name, value] of Object.entries(ticket.image.headers)) {
      headers[name.toLowerCase()] = value;
    }
    const parsed = PutHeaders.safeParse(headers);
    if (!parsed.success) invalid('upload headers');
    if (headers['content-type'] !== request.image.contentType) invalid('content type');
    if (headers['x-amz-checksum-sha256'] !== bytesToBase64(hexToBytes(request.image.sha256))) {
      invalid('checksum');
    }
    for (const url of [ticket.image.publicUrl, ticket.metadata.publicUrl]) {
      if (!url.includes(request.mint)) invalid('public URL not named after the mint');
      if (!isUnder(url, options.publicBaseUrl)) invalid('public URL outside the public bucket');
    }
    if (new TextEncoder().encode(ticket.metadata.publicUrl).length > 200) invalid('URL too long');
    return headers;
  }

  return {
    async uploadCoin(request, image) {
      const body = UploadRequest.parse(request);
      if (image.length !== body.image.size) {
        throw new UploadError('refused', 'The image size does not match its descriptor.');
      }

      // 1. Ticket.
      const res = await send(root, {
        method: 'POST',
        headers: forgeHeaders,
        body: JSON.stringify(body),
      });
      if (!res.ok) await refuse(res);
      let ticket: UploadTicket;
      try {
        const parsed = UploadTicket.safeParse(await res.json());
        if (!parsed.success) throw new Error('shape');
        ticket = parsed.data;
      } catch {
        throw new UploadError('invalid_answer', 'The FORGE upload service answer is invalid.');
      }
      const headers = checkTicket(ticket, body);

      // 2. Image PUT (write-once). A 412 on the first attempt means the key already existed: never
      //    overwrite. A 412 on a retry may be our own lost first attempt: `complete` re-checks the
      //    stored bytes against the SHA-256 either way.
      let attempt = 0;
      const put = await send(
        ticket.image.uploadUrl,
        { method: 'PUT', headers, body: image },
        (n) => {
          attempt = n;
        },
      );
      if (put.status === 412 && attempt === 0) {
        throw new UploadError('conflict', 'An image already exists for this coin. Try again.', 412);
      }
      if (!put.ok && put.status !== 412) {
        throw new UploadError('refused', 'The coin image upload failed. Try again.', put.status);
      }

      // 3. Complete: FORGE verifies the stored image and writes the metadata.
      const done = await send(`${root}/${encodeURIComponent(ticket.uploadId)}/complete`, {
        method: 'POST',
        headers: forgeHeaders,
        body: JSON.stringify({ mint: body.mint }),
      });
      if (!done.ok) await refuse(done);
      let receipt: UploadReceipt;
      try {
        const parsed = UploadReceipt.safeParse(await done.json());
        if (!parsed.success) throw new Error('shape');
        receipt = parsed.data;
      } catch {
        throw new UploadError('invalid_answer', 'The FORGE upload service answer is invalid.');
      }
      if (
        receipt.image.publicUrl !== ticket.image.publicUrl ||
        receipt.metadata.publicUrl !== ticket.metadata.publicUrl ||
        receipt.image.sha256 !== body.image.sha256
      ) {
        throw new UploadError('invalid_answer', 'The FORGE upload receipt does not match.');
      }
      return { imageUrl: receipt.image.publicUrl, metadataUrl: receipt.metadata.publicUrl };
    },
  };
}
